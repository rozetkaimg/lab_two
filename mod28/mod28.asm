.global _main
.align 2

_main:
    // Пролог функции - сохраняем регистры
    stp x29, x30, [sp, #-16]!   // Сохраняем FP и LR в стек
    sub sp, sp, #32              // Выделяем место в стеке для локальных переменных

    // Выводим приглашение для ввода
    adrp x0, prompt@PAGE         // Загружаем адрес строки приглашения
    add x0, x0, prompt@PAGEOFF   // Добавляем смещение
    bl _printf                   // Вызываем printf

    // Читаем ввод пользователя
    mov x0, #0                   // 0 = stdin
    adrp x1, input_buffer@PAGE   // Адрес буфера для ввода
    add x1, x1, input_buffer@PAGEOFF
    mov x2, #100                 // Максимальная длина ввода
    bl _read                     // Вызов read()

    // Инициализация переменных:
    mov x19, #0                  // x19 = счетчик чисел (результат)
    adrp x20, input_buffer@PAGE  // x20 = указатель на текущий символ ввода
    add x20, x20, input_buffer@PAGEOFF
    adrp x21, number_buffer@PAGE // x21 = буфер для текущего числа (как строка)
    add x21, x21, number_buffer@PAGEOFF

// Основной цикл разбора ввода
parse_loop:
    ldrb w22, [x20], #1          // Загружаем символ и двигаем указатель
    cbz w22, parse_done          // Если нулевой символ - конец строки
    cmp w22, ' '                 // Проверяем пробел
    b.eq parse_loop              // Пропускаем пробелы

    // Начало нового числа
    mov x23, x21                 // x23 = текущая позиция в буфере числа

// Сохраняем цифры числа
store_digit:
    strb w22, [x23], #1          // Сохраняем цифру и двигаем указатель
    ldrb w22, [x20], #1          // Читаем следующий символ
    cbz w22, process_number      // Если конец строки - обработать число
    cmp w22, ' '                 // Проверяем пробел
    b.ne store_digit             // Если не пробел - продолжаем

// Преобразуем строку в число и обрабатываем
process_number:
    mov w24, #0                  // Добавляем нулевой терминатор
    strb w24, [x23]
    
    // Конвертируем строку в число
    mov x0, x21
    bl _atoi                     // Вызов atoi()
    mov x25, x0                  // x25 = текущее число

    // Вычисляем сумму цифр
    mov x26, #0                  // x26 = сумма цифр
    mov x0, x25
    bl calculate_digit_sum       // Вызов функции расчета суммы
    mov x26, x0

    // Проверяем сумму > 10
    cmp x26, #10
    b.le next_number             // Если сумма <= 10 - пропускаем
    add x19, x19, #1             // Увеличиваем счетчик

// Переход к следующему числу
next_number:
    cbz w22, parse_done          // Если конец строки - завершаем
    b parse_loop                 // Иначе продолжаем разбор

// Вывод результата
parse_done:
    adrp x0, result_fmt@PAGE     // Загружаем формат строки вывода
    add x0, x0, result_fmt@PAGEOFF
    mov x1, x19                  // Передаем результат (счетчик)
    bl _printf                   // Выводим результат

    // Эпилог функции - восстанавливаем регистры и завершаем
    mov x0, #0                   // Код возврата 0
    add sp, sp, #32               // Освобождаем стек
    ldp x29, x30, [sp], #16      // Восстанавливаем FP и LR
    ret                          // Возврат из программы

// Функция вычисления суммы цифр числа
// Вход: x0 - число
// Выход: x0 - сумма цифр
calculate_digit_sum:
    stp x29, x30, [sp, #-16]!   // Пролог
    mov x1, #0                   // Инициализация суммы

// Цикл по цифрам числа
digit_loop:
    cbz x0, digit_done           // Если число == 0 - завершаем
    mov x2, #10                  // Для деления на 10
    udiv x3, x0, x2              // x3 = число / 10
    msub x4, x3, x2, x0          // x4 = цифра (число % 10)
    add x1, x1, x4               // Добавляем цифру к сумме
    mov x0, x3                   // Оставляем только необработанные цифры
    b digit_loop                 // Повторяем

digit_done:
    mov x0, x1                   // Возвращаем сумму
    ldp x29, x30, [sp], #16      // Эпилог
    ret

// Сегмент данных
.data
.align 4
prompt:     .asciz "Введите список чисел, разделенных пробелами: "
result_fmt: .asciz "Количество чисел с суммой цифр > 10: %d\n"
input_buffer: .space 100        // Буфер для ввода
number_buffer: .space 20        // Буфер для одного числа